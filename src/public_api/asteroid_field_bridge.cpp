std::expected<std::unique_ptr<Buffer>, std::string>
upload(Allocator& allocator, const void* data, VkDeviceSize size, BufferUsage usage,
       MemoryPlacement placement = MemoryPlacement::CpuToGpu)
{
    auto buffer = Buffer::create(allocator, {.size = size, .usage = usage, .memory = placement});
    if (!buffer) return std::unexpected(buffer.error());
    auto mapped = buffer->map();
    if (!mapped) return std::unexpected(mapped.error());
    std::memcpy(*mapped, data, static_cast<std::size_t>(size));
    auto flushed = buffer->flush();
    if (!flushed) return std::unexpected(flushed.error());
    buffer->unmap();
    return std::make_unique<Buffer>(std::move(*buffer));
}

