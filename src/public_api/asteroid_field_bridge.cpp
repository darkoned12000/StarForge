struct RawAsteroidField::Impl
{
    VkDevice device = VK_NULL_HANDLE;
    std::unique_ptr<Allocator> allocator;
    std::unique_ptr<Buffer> vertexBuffer;
    std::unique_ptr<Buffer> indexBuffer;
    std::unique_ptr<Buffer> nearInstances;
    std::unique_ptr<Buffer> farInstances;
    std::uint64_t vertexAddress = 0;
    std::uint32_t indexCount = 0;
    std::uint32_t capacity = 0;
    std::optional<environment::RockFieldRenderer> renderer;
};

RawAsteroidField::~RawAsteroidField() = default;
RawAsteroidField::RawAsteroidField(RawAsteroidField&&) noexcept = default;
RawAsteroidField& RawAsteroidField::operator=(RawAsteroidField&&) noexcept = default;

std::expected<std::unique_ptr<RawAsteroidField>, std::string>
RawAsteroidField::create(const CreateInfo& info)
{
    if (info.device == VK_NULL_HANDLE || info.instance == VK_NULL_HANDLE ||
        info.physicalDevice == VK_NULL_HANDLE)
        return std::unexpected("RawAsteroidField requires instance/device/physicalDevice");

    auto allocator = Allocator::create({
        .instance = info.instance, .physicalDevice = info.physicalDevice, .device = info.device});
    if (!allocator) return std::unexpected(allocator.error());

    // Seeded lumpy base mesh. `variantCount` variants are generated by the
    // gameplay layer's T1 proof; the GPU field uses the shared detailed mesh
    // with per-instance procedural shape variety (single draw call).
    // The tessellation has to be fine enough for the baked craters to
    // survive: at 20x28 a crater spanned barely one row of vertices and the
    // relief vanished, which is what made the rocks read as plain blobs.
    // 48x64 keeps the craters resolvable for a ~3.2k vertex mesh.
    auto mesh = environment::generateAsteroidMesh(1.0f, 48, 64, 0);
    if (mesh.vertices.empty() || mesh.indices.empty())
        return std::unexpected("RawAsteroidField: base mesh generation failed");

    auto vertexBuffer = upload(*allocator, mesh.vertices.data(),
                               mesh.vertices.size() * sizeof(float), BufferUsage::Storage);
    if (!vertexBuffer) return std::unexpected(vertexBuffer.error());
    auto indexBuffer = upload(*allocator, mesh.indices.data(),
                              mesh.indices.size() * sizeof(std::uint32_t), BufferUsage::Index);
    if (!indexBuffer) return std::unexpected(indexBuffer.error());

    const VkDeviceSize instanceBytes = static_cast<VkDeviceSize>(info.capacity) * sizeof(RawRockInstance);
    auto nearInstances = Buffer::create(*allocator, {
        .size = instanceBytes, .usage = BufferUsage::Storage, .memory = MemoryPlacement::CpuToGpu});
    if (!nearInstances) return std::unexpected(nearInstances.error());
    auto farInstances = Buffer::create(*allocator, {
        .size = instanceBytes, .usage = BufferUsage::Storage, .memory = MemoryPlacement::CpuToGpu});
    if (!farInstances) return std::unexpected(farInstances.error());

    auto renderer = environment::RockFieldRenderer::create({
        .device = info.device, .colorFormat = info.colorFormat, .depthFormat = info.depthFormat,
        .shaderDirectory = info.shaderDirectory, .specializationInfo = info.specializationInfo});
    if (!renderer) return std::unexpected(renderer.error());

    auto result = std::unique_ptr<RawAsteroidField>(new RawAsteroidField());
    auto impl = std::make_unique<Impl>();
    impl->device = info.device;
    impl->vertexAddress = (*vertexBuffer)->deviceAddress(info.device);
    impl->indexCount = static_cast<std::uint32_t>(mesh.indices.size());
    impl->capacity = info.capacity;
    impl->allocator = std::make_unique<Allocator>(std::move(*allocator));
    impl->vertexBuffer = std::move(*vertexBuffer);
    impl->indexBuffer = std::move(*indexBuffer);
    impl->nearInstances = std::make_unique<Buffer>(std::move(*nearInstances));
    impl->farInstances = std::make_unique<Buffer>(std::move(*farInstances));
    impl->renderer = std::move(*renderer);
    result->impl_ = std::move(impl);
    return result;
}

void RawAsteroidField::render(VkCommandBuffer cmd, const RawRockRenderContext& context,
                              const RawRockInstance* instances, std::uint32_t count)
{
    if (!impl_) return;
    auto& impl = *impl_;
    count = std::min(count, impl.capacity);

    std::vector<RawRockInstance> near;
    std::vector<RawRockInstance> far;
    near.reserve(count);
    far.reserve(count);

    const float lodSq = context.lodDistance * context.lodDistance;
    // World units per pixel at a given distance: 2*d / (projScaleY * resY).
    const float pixelsToWorld = 2.0f /
        std::max(context.projectionScale.y * context.resolution.y, 1.0f);

    for (std::uint32_t i = 0; i < count; ++i)
    {
        RawRockInstance inst = instances[i];
        const float dx = inst.position[0] - context.cameraPosition.x;
        const float dy = inst.position[1] - context.cameraPosition.y;
        const float dz = inst.position[2] - context.cameraPosition.z;
        const float distSq = dx * dx + dy * dy + dz * dz;
        if (distSq > lodSq)
        {
            far.push_back(inst);
            continue;
        }
        const float distance = std::sqrt(distSq);
        // Distance-aware outline: constant screen-space thickness.
        inst.tint[3] = std::clamp(context.outlineWidthPixels * distance * pixelsToWorld,
                                  0.002f, 0.25f);
        near.push_back(inst);
    }

    auto writeInstances = [&](Buffer& buffer, const std::vector<RawRockInstance>& data) {
        if (data.empty()) return;
        auto mapped = buffer.map();
        if (!mapped) return;
        std::memcpy(*mapped, data.data(), data.size() * sizeof(RawRockInstance));
        (void)buffer.flush();
        buffer.unmap();
    };
    writeInstances(*impl.nearInstances, near);
    writeInstances(*impl.farInstances, far);

    vkCmdBindIndexBuffer(cmd, impl.indexBuffer->handle(), 0, VK_INDEX_TYPE_UINT32);

    environment::RockRenderContext rctx;
    for (int c = 0; c < 4; ++c)
        for (int r = 0; r < 4; ++r)
            rctx.viewProj[c][r] = context.viewProj.columns[c][r];
    rctx.projectionScale = math::Vec2f{context.projectionScale.x, context.projectionScale.y};
    rctx.resolution = math::Vec2f{context.resolution.x, context.resolution.y};
    rctx.sunDirection =
        math::Vec3f{context.sunDirection.x, context.sunDirection.y, context.sunDirection.z};

    environment::RockDrawParams params;
    params.vertexAddress = impl.vertexAddress;
    params.nearInstanceAddress = impl.nearInstances->deviceAddress(impl.device);
    params.nearInstanceCount = static_cast<std::uint32_t>(near.size());
    params.farInstanceAddress = impl.farInstances->deviceAddress(impl.device);
    params.farInstanceCount = static_cast<std::uint32_t>(far.size());
    params.indexCount = impl.indexCount;
    params.outline = context.outline;
    impl.renderer->render(cmd, rctx, params);
}

std::expected<void, std::string> RawAsteroidField::recreate(const CreateInfo& info)
{
    auto recreated = create(info);
    if (!recreated) return std::unexpected(recreated.error());
    impl_ = std::move((*recreated)->impl_);
    return {};
}

